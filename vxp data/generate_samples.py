#!/usr/bin/env python3
"""
Synthetic DIBH sample data generator.

Produces GEN + DIBH file pairs targeting each DIBH type (A, B, C)
in both app-CSV (t,raw) and VXP formats.

Type classification (from determineDibhType.js):
  A: avgDibh >= 15s AND CV < 15%
  C: avgDibh < 10s  OR  CV >= 30%  (and not A)
  B: everything else

Usage:
    python generate_samples.py        # writes to ./type_samples/
    python generate_samples.py <dir>  # writes to <dir>/
"""

import csv
import math
import os
import random
import sys

# ── Signal constants ─────────────────────────────────────────────────────────

SAMPLE_RATE = 25          # Hz
DT = 1.0 / SAMPLE_RATE   # 0.04 s per sample
BASELINE = 10.0           # resting signal level (mm)
HOLD_LEVEL = 20.0         # breath-hold plateau level (mm)
# max_amp estimated by analyzeFiles = p95 - p10 ≈ HOLD_LEVEL - BASELINE = 10.0
# hold_th = BASELINE + 0.80 * 10 = 18.0   (signal must exceed this for hold)
# release_th = BASELINE + 0.50 * 10 = 15.0 (hold ends when signal drops below)
NOISE_STD = 0.10          # Gaussian noise added to all samples (σ in mm)
BREATHING_PERIOD = 5.0    # seconds per breath cycle

# ── Noise helper (Box-Muller, no numpy needed) ────────────────────────────────

def _noise(rng):
    u1 = rng.random()
    u2 = rng.random()
    z = math.sqrt(-2.0 * math.log(max(u1, 1e-15))) * math.cos(2.0 * math.pi * u2)
    return NOISE_STD * z


# ── Signal builders ───────────────────────────────────────────────────────────

def build_gen(duration_s, amplitude_fn, rng):
    """
    Normal breathing GEN signal.

    amplitude_fn(t) → breathing amplitude at time t.
    Returns [(t_seconds, amplitude), ...].

    CV target depends on how much amplitude_fn varies across cycles:
      constant A=5          → CV ≈ 1-2%   (Type A territory)
      A=5+1.5*sin(...)      → CV ≈ 21%    (Type B territory)
      A=5+3.0*sin(...)      → CV ≈ 42%    (Type C territory)
    """
    samples = []
    t = 0.0
    while t <= duration_s + 1e-9:
        A = amplitude_fn(t)
        y = BASELINE + A * math.sin(2.0 * math.pi * t / BREATHING_PERIOD) + _noise(rng)
        samples.append((round(t, 6), round(y, 6)))
        t += DT
    return samples


def build_dibh(hold_duration_s, rng, n_reps=3):
    """
    DIBH signal with n_reps breath-hold attempts.

    Structure:
      [4s prep at baseline]
      × n_reps:
        [2s inhale ramp baseline→hold]
        [hold_duration_s flat at hold level]
        [1s exhale ramp hold→baseline]
        [4s rest at baseline]  ← omitted after last rep
      [2s tail at baseline]

    With hold_duration_s=20 → measured avgDibh ≈ 20s → Type A
    With hold_duration_s=13 → measured avgDibh ≈ 13s → Type B
    With hold_duration_s= 7 → measured avgDibh ≈  7s → Type C
    """
    PREP_SEC    = 4.0
    INHALE_SEC  = 2.0
    EXHALE_SEC  = 1.0
    REST_SEC    = 4.0
    TAIL_SEC    = 2.0

    samples = []
    t = 0.0

    def flat(duration, level):
        nonlocal t
        n = int(round(duration * SAMPLE_RATE))
        for _ in range(n):
            samples.append((round(t, 6), round(level + _noise(rng), 6)))
            t += DT

    def ramp(duration, start, end):
        nonlocal t
        n = int(round(duration * SAMPLE_RATE))
        for i in range(n):
            frac = i / max(n - 1, 1)
            level = start + frac * (end - start)
            samples.append((round(t, 6), round(level + _noise(rng), 6)))
            t += DT

    flat(PREP_SEC, BASELINE)
    for rep in range(n_reps):
        ramp(INHALE_SEC, BASELINE, HOLD_LEVEL)
        flat(hold_duration_s, HOLD_LEVEL)
        ramp(EXHALE_SEC, HOLD_LEVEL, BASELINE)
        if rep < n_reps - 1:
            flat(REST_SEC, BASELINE)
    flat(TAIL_SEC, BASELINE)

    return samples


# ── File writers ──────────────────────────────────────────────────────────────

def write_app_csv(path, samples, type_label, category, hold_s=None):
    """Write app-internal t,raw CSV (two columns, seconds)."""
    with open(path, 'w', newline='', encoding='utf-8') as f:
        f.write(f'# DIBH Type target: {type_label}\n')
        f.write(f'# Category: {category}\n')
        if hold_s is not None:
            f.write(f'# Hold duration per rep: {hold_s}s\n')
        f.write(f'# Samples: {len(samples)}, Duration: {samples[-1][0]:.1f}s\n')
        f.write(f'# Generated by generate_samples.py\n')
        w = csv.writer(f)
        w.writerow(['t', 'raw'])
        for t, raw in samples:
            w.writerow([t, raw])


def write_vxp(path, samples, type_label, category, patient_id, hold_s=None):
    """Write Varian VXP format (timestamp in milliseconds)."""
    total_time = samples[-1][0] if samples else 0.0
    with open(path, 'w', encoding='utf-8') as f:
        f.write('[Header]\n')
        f.write('Version=1.6\n')
        f.write('Data_layout=amplitude,phase,timestamp,validflag,ttlin,mark,ttlout\n')
        f.write(f'Patient_ID={patient_id}\n')
        f.write('Date=8-5-2026\n')
        f.write(f'Total_study_time={total_time:.3f}\n')
        f.write(f'Samples_per_second={SAMPLE_RATE}\n')
        f.write('Scale_factor=1.0\n')
        f.write(f'# DIBH Type target: {type_label}\n')
        f.write(f'# Category: {category}\n')
        if hold_s is not None:
            f.write(f'# Hold duration per rep: {hold_s}s\n')
        f.write('[Data]\n')
        for t, raw in samples:
            ts_ms = round(t * 1000)
            f.write(f'{raw},0.0,{ts_ms},0,1,,0\n')


# ── Type configurations ───────────────────────────────────────────────────────
#
# CV is std(cycle_amps)/mean(cycle_amps)*100 where cycle_amp ~= 2*A(t).
# For A(t) = 5 + k*sin(2pi*t/60):  CV ~= (k/sqrt(2))/5 * 100 %
#   k=0.0  -> CV ~=  0-2%  (tiny noise only)
#   k=1.5  -> CV ~= 21%
#   k=3.0  -> CV ~= 42%

TYPE_CONFIGS = [
    {
        'label':       'A',
        'description': 'CV ~2%, avgDibh ~20s -> Type A (avgDibh >= 15 AND CV < 15)',
        'gen_amp':     lambda t: 5.0,
        'dibh_hold':   20.0,
        'gen_seed':    101,
        'dibh_seed':   102,
    },
    {
        'label':       'B',
        'description': 'CV ~21%, avgDibh ~13s -> Type B (10 <= avgDibh < 15, CV < 30)',
        'gen_amp':     lambda t: 5.0 + 1.5 * math.sin(2.0 * math.pi * t / 60.0),
        'dibh_hold':   13.0,
        'gen_seed':    201,
        'dibh_seed':   202,
    },
    {
        'label':       'C',
        'description': 'CV ~42%, avgDibh ~7s -> Type C (avgDibh < 10 AND CV >= 30)',
        'gen_amp':     lambda t: max(0.5, 5.0 + 3.0 * math.sin(2.0 * math.pi * t / 60.0)),
        'dibh_hold':   7.0,
        'gen_seed':    301,
        'dibh_seed':   302,
    },
]


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(script_dir, 'type_samples')
    os.makedirs(out_dir, exist_ok=True)

    DATE = '20260508'

    for cfg in TYPE_CONFIGS:
        label     = cfg['label']
        hold_s    = cfg['dibh_hold']
        patient   = f'TYPE_{label}'

        gen_samples  = build_gen(120.0, cfg['gen_amp'],  random.Random(cfg['gen_seed']))
        dibh_samples = build_dibh(hold_s,                random.Random(cfg['dibh_seed']))

        base_gen  = f'TYPE_{label}_GEN_{DATE}'
        base_dibh = f'TYPE_{label}_DIBH_{DATE}'

        write_app_csv(os.path.join(out_dir, base_gen  + '.csv'), gen_samples,  label, 'GEN')
        write_app_csv(os.path.join(out_dir, base_dibh + '.csv'), dibh_samples, label, 'DIBH', hold_s)
        write_vxp    (os.path.join(out_dir, base_gen  + '.vxp'), gen_samples,  label, 'GEN',  patient)
        write_vxp    (os.path.join(out_dir, base_dibh + '.vxp'), dibh_samples, label, 'DIBH', patient, hold_s)

        gen_dur  = gen_samples[-1][0]
        dibh_dur = dibh_samples[-1][0]
        print(f'Type {label}: {cfg["description"]}')
        print(f'  GEN  - {len(gen_samples):>5} samples, {gen_dur:.1f}s  ->  {base_gen}.[csv|vxp]')
        print(f'  DIBH - {len(dibh_samples):>5} samples, {dibh_dur:.1f}s  ->  {base_dibh}.[csv|vxp]')
        print()

    print(f'Output: {out_dir}')


if __name__ == '__main__':
    main()
